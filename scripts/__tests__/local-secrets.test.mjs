// Spec 008, plan-b decision 6, plan-c decision 3 and plan-d step 2: `just prod-local` generates
// its two secrets and four OAuth fillers on first use in a file ignored by git, and never anywhere
// else. Every write goes through a temporary file next to it, which never survives the run. Runs
// a copy of the script in a temporary tree.
import { execFileSync, spawn } from 'node:child_process';
import {
  chmodSync,
  copyFileSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from 'node:fs';
import { setTimeout as sleep } from 'node:timers/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterEach, describe, expect, it } from 'vitest';

const script = new URL('../local-secrets.sh', import.meta.url);
const serverExample = readFileSync(
  new URL('../../apps/server/.env.example', import.meta.url),
  'utf8',
);

/** @type {string[]} */
const trees = [];
afterEach(() => {
  for (const tree of trees.splice(0)) rmSync(tree, { recursive: true, force: true });
});

function tree() {
  const root = mkdtempSync(join(tmpdir(), 'local-secrets-'));
  trees.push(root);
  mkdirSync(join(root, 'scripts'));
  mkdirSync(join(root, 'infra'));
  copyFileSync(script, join(root, 'scripts', 'local-secrets.sh'));
  return root;
}

/** @param {string} dir @returns {string[]} */
function files(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) =>
    entry.isDirectory() ? files(join(dir, entry.name)) : [join(dir, entry.name)],
  );
}

const SECRETS = ['INTERNAL_API_SECRET', 'IP_HASH_KEY'];
const OAUTH = [
  'GOOGLE_CLIENT_ID',
  'GOOGLE_CLIENT_SECRET',
  'DISCORD_CLIENT_ID',
  'DISCORD_CLIENT_SECRET',
];
const SECRET = /^[A-Za-z0-9_-]{43}$/;
// A filler is obviously not a credential: no provider accepts it.
const FILLER = /^local-filler-[A-Za-z0-9_-]{43}$/;

/** @param {string} out */
function values(out) {
  return Object.fromEntries(
    readFileSync(out, 'utf8')
      .split('\n')
      .filter((line) => line && !line.startsWith('#'))
      .map((line) => [line.slice(0, line.indexOf('=')), line.slice(line.indexOf('=') + 1)]),
  );
}

/** @param {Record<string, string>} found */
function expectComplete(found) {
  expect(Object.keys(found)).toEqual([...SECRETS, ...OAUTH]);
  for (const name of SECRETS) expect(found[name]).toMatch(SECRET);
  for (const name of OAUTH) expect(found[name]).toMatch(FILLER);
  expect(new Set(Object.values(found)).size).toBe(6);
}

// The temporary file of the script: `mktemp` in infra/, `local.secrets.env.XXXXXX`.
/** @param {string} root */
function temporaries(root) {
  return readdirSync(join(root, 'infra')).filter((name) => name.startsWith('local.secrets.env.'));
}

/** @param {string} root @param {Record<string, string>} [env] */
function run(root, env = {}) {
  try {
    return execFileSync('bash', [join(root, 'scripts', 'local-secrets.sh')], {
      cwd: tmpdir(),
      env: { ...process.env, ...env },
      stdio: 'pipe',
    });
  } finally {
    // After every case, also a failed one, no temporary file is left behind.
    expect(temporaries(root)).toEqual([]);
  }
}

const HEADER =
  '# Generated by scripts/local-secrets.sh for `just prod-local` only. Never copy to Coolify.\n';
const KEPT = `INTERNAL_API_SECRET=${'a'.repeat(43)}\nIP_HASH_KEY=${'b'.repeat(43)}\n`;
const OLD_FILLER = `local-filler-${'c'.repeat(43)}`;

/**
 * A `head` first in PATH, to act in the middle of the script: `secret()` calls it once per value.
 * @param {string} root @param {string} body shell run before the real head
 */
function shim(root, body) {
  const bin = join(root, 'bin');
  mkdirSync(bin);
  const head = execFileSync('sh', ['-c', 'command -v head'], { encoding: 'utf8' }).trim();
  writeFileSync(join(bin, 'head'), `#!/bin/sh\n${body}\nexec ${head} "$@"\n`, { mode: 0o755 });
  return { PATH: `${bin}:${process.env.PATH}` };
}

/**
 * Starts the script with a `head` that blocks, waits for its temporary file and sends TERM to the
 * whole process group (what Ctrl-C does with INT). Resolves with the exit code and signal.
 * @param {string} root
 */
async function interrupted(root) {
  const env = shim(root, 'sleep 30');
  const child = spawn('bash', [join(root, 'scripts', 'local-secrets.sh')], {
    cwd: tmpdir(),
    env: { ...process.env, ...env },
    detached: true,
    stdio: 'ignore',
  });
  const exited = new Promise((resolve) =>
    child.on('exit', (code, signal) => resolve({ code, signal })),
  );
  const deadline = Date.now() + 3_000;
  while (temporaries(root).length === 0) {
    if (Date.now() > deadline) throw new Error('the script never created its temporary file');
    await sleep(20);
  }
  process.kill(-(/** @type {number} */ (child.pid)), 'SIGTERM');
  return exited;
}

describe('local-secrets.sh', () => {
  it('creates only infra/local.secrets.env, with two secrets, four fillers and mode 600', () => {
    const root = tree();
    run(root);
    const out = join(root, 'infra', 'local.secrets.env');
    expect(files(root).sort()).toEqual([out, join(root, 'scripts', 'local-secrets.sh')].sort());
    expect(statSync(out).mode & 0o777).toBe(0o600);
    const found = values(out);
    expectComplete(found);
    // Never the public development values of the .env.example.
    for (const value of Object.values(found)) expect(serverExample).not.toContain(value);
  });

  it('completes a file of phase B with the four fillers, keeping its bytes', () => {
    const root = tree();
    const out = join(root, 'infra', 'local.secrets.env');
    const phaseB =
      '# Generated by scripts/local-secrets.sh for `just prod-local` only. Never copy to Coolify.\n' +
      `INTERNAL_API_SECRET=${'a'.repeat(43)}\n` +
      `IP_HASH_KEY=${'b'.repeat(43)}\n`;
    writeFileSync(out, phaseB, { mode: 0o644 });
    run(root);
    const text = readFileSync(out, 'utf8');
    // IP_HASH_KEY does not rotate: the file of B is a prefix, byte for byte.
    expect(text.startsWith(phaseB)).toBe(true);
    expectComplete(values(out));
    expect(statSync(out).mode & 0o777).toBe(0o600);
    // And a second run keeps the completed file.
    run(root);
    expect(readFileSync(out, 'utf8')).toBe(text);
  });

  it('repairs an interrupted append keeping both secrets byte for byte', () => {
    const root = tree();
    const out = join(root, 'infra', 'local.secrets.env');
    // Two of the four fillers and a cut line: an append of the old script cut halfway.
    writeFileSync(
      out,
      HEADER +
        KEPT +
        '# Fillers for the OAuth credentials the server requires outside loopback (plan-c).\n' +
        '# They are not credentials: no provider accepts them.\n' +
        `GOOGLE_CLIENT_ID=${OLD_FILLER}\n` +
        `GOOGLE_CLIENT_SECRET=${OLD_FILLER}\n` +
        'DISCORD_CLIE',
      { mode: 0o644 },
    );
    run(root);
    const text = readFileSync(out, 'utf8');
    expect(text.startsWith(HEADER + KEPT)).toBe(true);
    const found = values(out);
    expectComplete(found);
    for (const name of OAUTH) expect(found[name]).not.toBe(OLD_FILLER);
    expect(statSync(out).mode & 0o777).toBe(0o600);
    run(root);
    expect(readFileSync(out, 'utf8')).toBe(text);
  });

  it('drops duplicated and malformed OAuth lines and writes exactly four new fillers', () => {
    for (const extra of [
      `GOOGLE_CLIENT_ID=${OLD_FILLER}\nGOOGLE_CLIENT_ID=${OLD_FILLER}\n`,
      'DISCORD_CLIENT_ID=local-filler-x\n',
      'GOOGLE_CLIENT_ID=\n',
      `GOOGLE_CLIENT_ID=${OLD_FILLER}\nGOOGLE_CLIENT_SECRET=${OLD_FILLER}\nDISCORD_CLIENT_ID=${OLD_FILLER}\nDISCORD_CLIENT_SECRET=${OLD_FILLER}\nDISCORD_CLIENT_SECRET=local-filler-x\n`,
    ]) {
      const root = tree();
      const out = join(root, 'infra', 'local.secrets.env');
      writeFileSync(out, HEADER + KEPT + extra);
      run(root);
      const lines = readFileSync(out, 'utf8').split('\n');
      for (const name of OAUTH) {
        expect(lines.filter((line) => line.startsWith(`${name}=`))).toHaveLength(1);
      }
      expect(lines).toContain(`INTERNAL_API_SECRET=${'a'.repeat(43)}`);
      expect(lines).toContain(`IP_HASH_KEY=${'b'.repeat(43)}`);
      const found = values(out);
      expectComplete(found);
      for (const name of OAUTH) expect(found[name]).not.toBe(OLD_FILLER);
    }
  });

  it('completes a file without a final newline, each variable on its own line', () => {
    const root = tree();
    const out = join(root, 'infra', 'local.secrets.env');
    writeFileSync(out, HEADER + KEPT.slice(0, -1));
    run(root);
    const text = readFileSync(out, 'utf8');
    expect(text.startsWith(HEADER + KEPT)).toBe(true);
    expect(text.endsWith('\n')).toBe(true);
    const found = values(out);
    expectComplete(found);
    expect(found.IP_HASH_KEY).toBe('b'.repeat(43));
    // The second run neither rotates nor rewrites it.
    run(root);
    expect(readFileSync(out, 'utf8')).toBe(text);
  });

  it('never overwrites a file that appears while it is being created', () => {
    const root = tree();
    const out = join(root, 'infra', 'local.secrets.env');
    // The first `head` creates the file between the check and the write.
    const env = shim(root, `[ -e "${out}" ] || printf 'RACE\\n' >"${out}"`);
    expect(() => run(root, env)).toThrow();
    expect(readFileSync(out, 'utf8')).toBe('RACE\n');
  });

  it('leaves no temporary file and no secrets file when TERM cuts a creation', async () => {
    const root = tree();
    const { code, signal } = await interrupted(root);
    expect(code === 0 && signal === null).toBe(false);
    expect(temporaries(root)).toEqual([]);
    expect(readdirSync(join(root, 'infra'))).toEqual([]);
  });

  it('leaves the file untouched and no temporary file when TERM cuts a repair', async () => {
    const root = tree();
    const out = join(root, 'infra', 'local.secrets.env');
    writeFileSync(out, HEADER + KEPT, { mode: 0o600 });
    const { code, signal } = await interrupted(root);
    expect(code === 0 && signal === null).toBe(false);
    expect(temporaries(root)).toEqual([]);
    expect(readFileSync(out, 'utf8')).toBe(HEADER + KEPT);
  });

  it('is idempotent: a second run keeps the file as it is', () => {
    const root = tree();
    run(root);
    const out = join(root, 'infra', 'local.secrets.env');
    const first = readFileSync(out, 'utf8');
    run(root);
    expect(readFileSync(out, 'utf8')).toBe(first);
  });

  it('keeps a valid existing file and tightens its mode to 600', () => {
    const root = tree();
    run(root);
    const out = join(root, 'infra', 'local.secrets.env');
    const first = readFileSync(out, 'utf8');
    chmodSync(out, 0o644);
    run(root);
    expect(readFileSync(out, 'utf8')).toBe(first);
    expect(statSync(out).mode & 0o777).toBe(0o600);
  });

  it('regenerates an existing file that is empty or lost a secret', () => {
    for (const content of ['', '# Generated\nINTERNAL_API_SECRET=\n', 'INTERNAL_API_SECRET=x\n']) {
      const root = tree();
      const out = join(root, 'infra', 'local.secrets.env');
      writeFileSync(out, content);
      run(root);
      expectComplete(values(out));
      expect(statSync(out).mode & 0o777).toBe(0o600);
    }
  });

  it('is ignored, with its temporary file, by git and by the Docker build context', () => {
    const gitignore = readFileSync(new URL('../../.gitignore', import.meta.url), 'utf8');
    const dockerignore = readFileSync(new URL('../../.dockerignore', import.meta.url), 'utf8');
    // The pattern also covers a temporary file that a `kill -9` left behind.
    expect(gitignore.split('\n')).toContain('infra/local.secrets.env*');
    expect(dockerignore.split('\n')).toContain('infra/local.secrets.env*');
    const repo = new URL('../..', import.meta.url).pathname;
    for (const path of ['infra/local.secrets.env', 'infra/local.secrets.env.abc123']) {
      execFileSync('git', ['check-ignore', '-q', '--no-index', path], { cwd: repo });
    }
  });
});
