#!/usr/bin/env bash
# Spec 008, plan-b decision 6: the secrets of `just prod-local`. Its origin (https://localhost) is
# "outside loopback", where the server refuses the public values of apps/server/.env.example, and
# a fixed value committed to git would be accepted by the production binary too. So they are
# generated on first use (32 bytes of /dev/urandom each, base64url without padding) into
# infra/local.secrets.env, which git and .dockerignore ignore (`infra/local.secrets.env*`, which
# also covers the temporary file below). A valid file keeps its content (its mode is set to 600).
#
# Plan-c decision 3: outside loopback the server also requires the four OAuth credentials. Here
# they are fillers (`local-filler-` and 32 random bytes) that no provider accepts: prod-local has
# no working login.
#
# Plan-d step 2, the repair rule: when both secrets are valid but the fillers are not (a file of
# phase B, an append cut halfway, a duplicated or malformed OAuth line, no final newline), the
# header comment and the INTERNAL_API_SECRET= and IP_HASH_KEY= lines are kept byte for byte and
# in their order; every other line (all OAuth lines and their comments, also duplicated,
# malformed or cut ones) is dropped and the four fillers are regenerated. So IP_HASH_KEY never
# rotates. A file without both secrets (empty, truncated) is regenerated from scratch.
#
# Every write goes through a temporary file in infra/ (same filesystem), mode 600, removed on
# EXIT, INT and TERM. An existing file is replaced with `mv` (atomic: never half written); a new
# one is published with `ln`, which fails if the file appeared meanwhile (noclobber semantics).
# Prints nothing: the values never reach the terminal.
set -eu

root="$(cd "$(dirname "$0")/.." && pwd)"
file="$root/infra/local.secrets.env"
oauth="GOOGLE_CLIENT_ID GOOGLE_CLIENT_SECRET DISCORD_CLIENT_ID DISCORD_CLIENT_SECRET"
# shellcheck disable=SC2016 # literal backticks: a comment line, nothing expands
header='# Generated by scripts/local-secrets.sh for `just prod-local` only. Never copy to Coolify.'
secret_re='[A-Za-z0-9_-]{43}'

tmp=""
cleanup() {
    if [ -n "$tmp" ]; then
        rm -f "$tmp"
    fi
}
trap cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM

# Both secrets well formed, each exactly once. Otherwise compose would fail with "missing a
# value" or pick one of two values.
secrets_valid() {
    [ "$(grep -Ec "^INTERNAL_API_SECRET=$secret_re$" "$file")" = 1 ] &&
        [ "$(grep -c '^INTERNAL_API_SECRET=' "$file")" = 1 ] &&
        [ "$(grep -Ec "^IP_HASH_KEY=$secret_re$" "$file")" = 1 ] &&
        [ "$(grep -c '^IP_HASH_KEY=' "$file")" = 1 ]
}
# The four fillers, each exactly once and well formed.
oauth_valid() {
    for name in $oauth; do
        [ "$(grep -Ec "^$name=local-filler-$secret_re$" "$file")" = 1 ] || return 1
        [ "$(grep -c "^$name=" "$file")" = 1 ] || return 1
    done
}
# Kept as it is only if it also ends with a newline: the next line written never glues onto it.
ends_with_newline() {
    [ ! -s "$file" ] || [ "$(tail -c 1 "$file" | od -An -c | tr -d ' ')" = '\n' ]
}

secret() {
    head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n'
}

fillers() {
    printf '# Fillers for the OAuth credentials the server requires outside loopback (plan-c).\n'
    printf '# They are not credentials: no provider accepts them.\n'
    for name in $oauth; do
        printf '%s=local-filler-%s\n' "$name" "$(secret)"
    done
}

umask 077

if [ -e "$file" ] && secrets_valid && oauth_valid && ends_with_newline; then
    # Kept as it is, but never readable by others (it may come from an older version).
    chmod 600 "$file"
    exit 0
fi

# Decided once, before writing: a file that appears after this point is never overwritten.
existed=0
if [ -e "$file" ]; then
    existed=1
fi

tmp="$(mktemp "$file.XXXXXX")"
chmod 600 "$tmp"

if [ "$existed" = 1 ] && secrets_valid; then
    # The repair rule. grep ends every kept line with a newline, also the last one of the file.
    {
        grep -E "^(# Generated by scripts/local-secrets\.sh |INTERNAL_API_SECRET=$secret_re$|IP_HASH_KEY=$secret_re$)" "$file"
        fillers
    } >"$tmp"
    mv -f "$tmp" "$file"
    tmp=""
    exit 0
fi

{
    printf '%s\n' "$header"
    printf 'INTERNAL_API_SECRET=%s\n' "$(secret)"
    printf 'IP_HASH_KEY=%s\n' "$(secret)"
    fillers
} >"$tmp"

if [ "$existed" = 1 ]; then
    # Empty or without both secrets: nothing to keep.
    mv -f "$tmp" "$file"
    tmp=""
else
    # Fails if the file appeared between the test and here, instead of overwriting it. The
    # temporary name is removed by the trap.
    ln "$tmp" "$file"
fi
